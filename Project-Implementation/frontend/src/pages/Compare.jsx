import React, { useState, useEffect } from 'react';
import { useSearchParams, Link } from 'react-router-dom';
import api from '../api/axios';
import {
  GitCompare,
  Plus,
  Trash2,
  Download,
  Copy,
  Check,
  BookOpen,
  ArrowRight,
  ExternalLink,
  Target,
  Sparkles,
  Layers,
  FlaskConical,
} from 'lucide-react';
import { useToast } from '../context/ToastContext';

export default function Compare() {
  const [searchParams, setSearchParams] = useSearchParams();
  const { showToast } = useToast();

  const [availablePapers, setAvailablePapers] = useState([]);
  const [selectedIds, setSelectedIds] = useState([]);
  const [comparisonData, setComparisonData] = useState([]);
  const [loading, setLoading] = useState(false);
  const [copied, setCopied] = useState(false);

  // Initial load: parse query param ?ids=a,b
  useEffect(() => {
    api.get('/papers?limit=50').then((res) => {
      if (res.data?.success) {
        const list = res.data.data.papers || [];
        setAvailablePapers(list);

        const idsParam = searchParams.get('ids');
        if (idsParam) {
          const parsed = idsParam.split(',').filter(Boolean);
          setSelectedIds(parsed.slice(0, 4));
        } else if (list.length >= 2) {
          setSelectedIds([list[0]._id, list[1]._id]);
        }
      }
    });
  }, []);

  // Fetch comparison matrix whenever selectedIds change
  useEffect(() => {
    if (selectedIds.length >= 2) {
      setLoading(true);
      api.post('/papers/compare', { paperIds: selectedIds })
        .then((res) => {
          if (res.data?.success) {
            setComparisonData(res.data.data.comparison || []);
          }
        })
        .catch((err) => {
          showToast('Failed to compare papers', 'error');
        })
        .finally(() => setLoading(false));

      setSearchParams({ ids: selectedIds.join(',') });
    } else {
      setComparisonData([]);
    }
  }, [selectedIds]);

  const handleTogglePaper = (id) => {
    if (selectedIds.includes(id)) {
      if (selectedIds.length <= 2) {
        showToast('At least 2 papers are required for comparison', 'info');
        return;
      }
      setSelectedIds((prev) => prev.filter((p) => p !== id));
    } else {
      if (selectedIds.length >= 4) {
        showToast('Maximum 4 papers can be compared simultaneously', 'info');
        return;
      }
      setSelectedIds((prev) => [...prev, id]);
    }
  };

  const exportMarkdown = () => {
    if (!comparisonData.length) return;

    let md = `# Research Paper Comparison Matrix\n\n`;
    md += `*Generated by Cloud-Native AI Research Discovery Platform on ${new Date().toLocaleDateString()}*\n\n`;

    dimensions.forEach((dim) => {
      md += `## ${dim.title}\n\n`;
      comparisonData.forEach((item, idx) => {
        md += `### [${idx + 1}] ${item.paper.title}\n`;
        const val = dim.getValue(item);
        if (Array.isArray(val)) {
          val.forEach((v) => { md += `- ${v}\n`; });
        } else {
          md += `${val || 'Not reported'}\n`;
        }
        md += `\n`;
      });
    });

    navigator.clipboard.writeText(md);
    setCopied(true);
    showToast('Comparison matrix copied to clipboard as Markdown!', 'success');
    setTimeout(() => setCopied(false), 2000);
  };

  const dimensions = [
    {
      id: 'problem',
      title: 'Research Problem & Bottlenecks',
      getValue: (item) => item.analysis?.researchProblem || item.paper.researchDomain || 'Domain challenge',
    },
    {
      id: 'objectives',
      title: 'Objectives & Hypotheses',
      getValue: (item) => item.analysis?.objectives || 'Empirical optimization and analysis',
    },
    {
      id: 'methodology',
      title: 'Methodology & Workflow',
      getValue: (item) => item.analysis?.methodology || 'Experimental benchmarking and prototype implementation',
    },
    {
      id: 'algorithms',
      title: 'Algorithms & Models',
      getValue: (item) => item.analysis?.algorithms || [],
    },
    {
      id: 'technologies',
      title: 'Technologies & Frameworks',
      getValue: (item) => item.analysis?.technologies || [],
    },
    {
      id: 'datasets',
      title: 'Datasets & Setup',
      getValue: (item) => item.analysis?.datasets || [],
    },
    {
      id: 'results',
      title: 'Quantitative Results & Findings',
      getValue: (item) => item.analysis?.experimentalResults?.length ? item.analysis.experimentalResults : item.analysis?.majorFindings || [],
    },
    {
      id: 'contributions',
      title: 'Contributions & Novelty',
      getValue: (item) => item.analysis?.contributionsNovelty?.length ? item.analysis.contributionsNovelty : item.analysis?.majorFindings || [],
    },
    {
      id: 'limitations',
      title: 'Documented Limitations',
      getValue: (item) => item.analysis?.limitations || item.analysis?.authorLimitations || [],
    },
    {
      id: 'gaps',
      title: 'Identified Research Gaps',
      getValue: (item) => item.analysis?.researchGaps || [],
    },
    {
      id: 'futureScope',
      title: 'Future Scope',
      getValue: (item) => item.analysis?.futureDirections || [],
    },
  ];

  return (
    <div className="max-w-7xl mx-auto space-y-6 pb-20">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h1 className="text-2xl sm:text-3xl font-extrabold text-white tracking-tight flex items-center space-x-3">
            <GitCompare className="w-7 h-7 text-indigo-400" />
            <span>Research Paper Comparison Matrix</span>
          </h1>
          <p className="text-slate-400 text-sm mt-1">
            Compare 2 to 4 papers side-by-side across methodology, algorithms, datasets, metrics, limitations, and research gaps.
          </p>
        </div>

        <div className="flex items-center space-x-3">
          <button
            onClick={exportMarkdown}
            disabled={!comparisonData.length}
            className="px-4 py-2 bg-indigo-600 hover:bg-indigo-500 disabled:opacity-40 text-white rounded-xl text-xs font-semibold flex items-center space-x-2 transition shadow-md shadow-indigo-600/30"
          >
            {copied ? <Check className="w-4 h-4 text-emerald-300" /> : <Copy className="w-4 h-4" />}
            <span>{copied ? 'Copied Markdown' : 'Export Matrix (Markdown)'}</span>
          </button>
        </div>
      </div>

      {/* Paper Selector Chips */}
      <div className="p-4 bg-slate-950/80 border border-slate-800 rounded-2xl shadow space-y-3">
        <div className="flex items-center justify-between">
          <span className="text-xs font-bold text-slate-300">
            Selected for Comparison ({selectedIds.length}/4)
          </span>
          <span className="text-[11px] text-slate-500">
            Click available papers below to add or remove
          </span>
        </div>

        <div className="flex flex-wrap gap-2">
          {availablePapers.map((paper) => {
            const isSelected = selectedIds.includes(paper._id);
            return (
              <button
                key={paper._id}
                onClick={() => handleTogglePaper(paper._id)}
                className={`px-3 py-1.5 rounded-xl text-xs font-semibold flex items-center space-x-1.5 transition border ${
                  isSelected
                    ? 'bg-indigo-600 text-white border-indigo-500 shadow-sm'
                    : 'bg-slate-900 text-slate-400 border-slate-800 hover:text-slate-200 hover:bg-slate-800'
                }`}
              >
                <span className="truncate max-w-[200px]">{paper.title}</span>
                {isSelected ? <Check className="w-3.5 h-3.5" /> : <Plus className="w-3.5 h-3.5" />}
              </button>
            );
          })}
        </div>
      </div>

      {/* Comparison Matrix Table */}
      {loading ? (
        <div className="py-24 text-center space-y-3">
          <div className="w-10 h-10 border-3 border-indigo-500/30 border-t-indigo-500 rounded-full animate-spin mx-auto" />
          <p className="text-slate-400 text-sm">Aggregating cross-paper comparative dimensions...</p>
        </div>
      ) : comparisonData.length < 2 ? (
        <div className="py-16 text-center text-slate-500 text-xs bg-slate-950/40 rounded-2xl border border-slate-800 p-8 space-y-3">
          <GitCompare className="w-10 h-10 text-slate-600 mx-auto" />
          <p className="text-sm font-semibold text-slate-300">Select at least 2 papers to compare</p>
          <p>Click the chips above or select papers from your Library or Collections.</p>
        </div>
      ) : (
        <div className="bg-slate-950/80 border border-slate-800 rounded-2xl overflow-hidden shadow-2xl">
          <div className="overflow-x-auto">
            <table className="w-full text-left border-collapse min-w-[700px]">
              {/* Paper Headers */}
              <thead>
                <tr className="border-b border-slate-800 bg-slate-900/90">
                  <th className="p-4 text-xs font-extrabold text-slate-400 uppercase tracking-wider w-1/5 bg-slate-900/60 sticky left-0 z-10">
                    Dimension
                  </th>
                  {comparisonData.map((item, idx) => (
                    <th key={item.paper._id} className="p-4 text-xs font-bold text-white border-l border-slate-800">
                      <div className="space-y-1">
                        <span className="text-[10px] font-semibold text-indigo-400 uppercase tracking-wider">
                          Paper {idx + 1}
                        </span>
                        <h4 className="text-sm font-bold text-white line-clamp-2 leading-tight">
                          {item.paper.title}
                        </h4>
                        <p className="text-[11px] text-slate-400">
                          {(item.paper.authors || []).map((a) => a.name || a).slice(0, 2).join(', ')} ({item.paper.publicationYear || 'Recent'})
                        </p>
                        <Link
                          to={`/papers/${item.paper._id}`}
                          className="text-[11px] text-indigo-400 hover:underline inline-flex items-center space-x-1 pt-0.5"
                        >
                          <span>Open Full Details</span>
                          <ExternalLink className="w-2.5 h-2.5" />
                        </Link>
                      </div>
                    </th>
                  ))}
                </tr>
              </thead>

              {/* Dimension Rows */}
              <tbody className="divide-y divide-slate-800/80 text-xs text-slate-300">
                {dimensions.map((dim) => (
                  <tr key={dim.id} className="hover:bg-slate-900/40 transition">
                    <td className="p-4 font-bold text-slate-300 bg-slate-900/30 sticky left-0 z-10 border-r border-slate-800/80 align-top">
                      {dim.title}
                    </td>

                    {comparisonData.map((item) => {
                      const val = dim.getValue(item);
                      return (
                        <td key={item.paper._id} className="p-4 border-l border-slate-800 align-top leading-relaxed">
                          {Array.isArray(val) ? (
                            val.length > 0 ? (
                              <ul className="space-y-1 list-disc list-inside">
                                {val.map((v, vi) => (
                                  <li key={vi} className="text-slate-300">
                                    {v}
                                  </li>
                                ))}
                              </ul>
                            ) : (
                              <span className="text-slate-500 italic">None reported</span>
                            )
                          ) : (
                            <span>{val || <span className="text-slate-500 italic">None reported</span>}</span>
                          )}
                        </td>
                      );
                    })}
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </div>
      )}
    </div>
  );
}
